/**
 * Generates the SQL seed files from the deterministic demo dataset (src/lib/demo):
 *
 *   supabase/seed.sql        the REAL catalog skeleton (Harvard + courses + offerings). No assignments, no ratings.
 *   supabase/seed-demo.sql   DEMO / SYNTHETIC assignments, problems, demo users, and synthetic ratings.
 *   supabase/remove-demo.sql removes everything seed-demo.sql added, leaving the real catalog intact.
 *
 * Ids are the same name-derived UUIDs the in-browser demo uses, so both agree.
 * Usage: npm run gen:demo-sql
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildDemoDataset } from '../src/lib/demo/dataset.ts'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/

type Sql = string | number | boolean | null | undefined

function lit(v: Sql): string {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error(`non-finite number ${v}`)
    return String(v)
  }
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  return `'${v.replace(/'/g, "''")}'`
}

function row(values: Sql[]) {
  return `  (${values.map(lit).join(', ')})`
}

function chunk<T>(xs: T[], n: number): T[][] {
  const out: T[][] = []
  for (let i = 0; i < xs.length; i += n) out.push(xs.slice(i, i + n))
  return out
}

function assert(cond: unknown, msg: string): asserts cond {
  if (!cond) throw new Error(`gen-demo-sql: ${msg}`)
}

function assertUnique(keys: string[], what: string) {
  const seen = new Set<string>()
  for (const k of keys) {
    assert(!seen.has(k), `duplicate ${what}: ${k}`)
    seen.add(k)
  }
}

const ds = buildDemoDataset()

// ── sanity checks: the generated rows must satisfy the schema's constraints ──
for (const x of [...ds.universities, ...ds.courses, ...ds.offerings, ...ds.assignments, ...ds.problems]) {
  assert(SLUG_RE.test(x.slug), `invalid slug "${x.slug}"`)
}
assertUnique(ds.courses.map((c) => `${c.university_id}/${c.slug}`), 'course slug')
assertUnique(ds.offerings.map((o) => `${o.course_id}/${o.slug}`), 'offering slug')
assertUnique(ds.assignments.map((a) => `${a.course_offering_id}/${a.slug}`), 'assignment slug')
assertUnique(ds.problems.map((p) => `${p.assignment_id}/${p.slug}`), 'problem slug')
assertUnique(ds.ratings.map((r) => `${r.user_id}/${r.problem_id}`), 'rating (user, problem)')
const parentIds = new Set(ds.problems.map((p) => p.parent_problem_id).filter(Boolean))
for (const r of ds.ratings) {
  assert(!parentIds.has(r.problem_id), `rating on a problem with parts (${r.problem_id})`)
  assert(r.difficulty >= 1 && r.difficulty <= 10 && Number.isInteger(r.difficulty), `bad difficulty ${r.difficulty}`)
  assert(r.time_minutes == null || (r.time_minutes >= 1 && r.time_minutes <= 6000), `bad time ${r.time_minutes}`)
}

const GENERATED = '-- GENERATED by scripts/gen-demo-sql.ts (npm run gen:demo-sql) from src/lib/demo. Do not edit by hand.'

// ── catalog skeleton (shared by seed.sql and seed-demo.sql) ──
function catalogSql() {
  const u = ds.universities
  const lines: string[] = []
  lines.push('insert into public.universities (id, name, short_name, slug, domain, status)')
  lines.push('values')
  lines.push(u.map((x) => row([x.id, x.name, x.short_name, x.slug, x.domain, 'active'])).join(',\n'))
  lines.push('on conflict do nothing;')
  lines.push('')
  // Joined against the parent so a pre-existing conflicting row never causes a foreign-key error.
  lines.push('insert into public.courses (id, university_id, code, name, description, slug, department, status)')
  lines.push("select v.id::uuid, u.id, v.code, v.name, v.description, v.slug, v.department, 'active'")
  lines.push('  from (values')
  lines.push(ds.courses.map((c) => row([c.id, c.university_id, c.code, c.name, c.description, c.slug, c.department ?? null])).join(',\n'))
  lines.push('  ) as v (id, university_id, code, name, description, slug, department)')
  lines.push('  join public.universities u on u.id = v.university_id::uuid')
  lines.push('on conflict do nothing;')
  lines.push('')
  lines.push('insert into public.course_offerings (id, course_id, year, term, section, instructor, slug, status)')
  lines.push("select v.id::uuid, c.id, v.year::int, v.term::public.term, v.section, v.instructor, v.slug, 'active'")
  lines.push('  from (values')
  lines.push(ds.offerings.map((o) => row([o.id, o.course_id, o.year, o.term, o.section, o.instructor, o.slug])).join(',\n'))
  lines.push('  ) as v (id, course_id, year, term, section, instructor, slug)')
  lines.push('  join public.courses c on c.id = v.course_id::uuid')
  lines.push('on conflict do nothing;')
  return lines.join('\n')
}

const seedSql = `${GENERATED}
--
-- REAL catalog skeleton: Harvard University, its courses, and their course offerings (status 'active').
-- No assignments, problems, or ratings. Idempotent: safe to run more than once.
-- Ids match the deterministic ids used by the demo dataset, so supabase/seed-demo.sql lines up with it.

${catalogSql()}
`

// ── demo data ──
const demoUserIdList = ds.demoUserIds.map(lit).join(', ')
const demo: string[] = []
demo.push(`${GENERATED}
--
-- ============================================================================================================
--   DEMO / SYNTHETIC DATA. NOT REAL.
--   Everything below is made up for demonstration: ${ds.demoUserIds.length} fake users, ${ds.assignments.length} illustrative assignments
--   with ${ds.problems.length} original, generic problems (not taken from any real course), and ${ds.ratings.length} synthetic ratings.
--   Every demo row is flagged: profiles.is_demo and assignments.is_demo (problems belong to demo assignments).
--   Remove it all with supabase/remove-demo.sql; the real catalog (supabase/seed.sql) is left untouched.
-- ============================================================================================================
--
-- Run as the service role / postgres (auth.uid() is null), so the per-user rate limits in the ratings trigger
-- don't apply. Ratings are inserted normally: the triggers stamp the rating epoch and maintain problem_stats.

begin;

-- Catalog skeleton (identical to supabase/seed.sql; no-op if already present).
${catalogSql()}

-- Demo users. The on_auth_user_created trigger creates their profiles, which are then flagged is_demo.
insert into auth.users (id, email, raw_user_meta_data)
values
${ds.demoUserIds.map((id, i) => row([id, `demo-user-${i}@demo.hardest.invalid`, '{"demo": true}'])).join(',\n')}
on conflict (id) do nothing;

insert into public.profiles (id) select id from auth.users where id in (${demoUserIdList}) on conflict (id) do nothing;
update public.profiles set is_demo = true, show_name = false where id in (${demoUserIdList});

-- Demo assignments (is_demo = true).
insert into public.assignments (id, course_offering_id, title, slug, assignment_type, assignment_number, display_order,
                                due_date, description, is_demo, created_by, created_at, updated_at)
select v.id::uuid, o.id, v.title, v.slug, v.assignment_type::public.assignment_type, v.assignment_number::numeric,
       v.display_order::int, v.due_date::date, v.description, true, null, v.created_at::timestamptz, v.created_at::timestamptz
  from (values
${ds.assignments.map((a) => row([a.id, a.course_offering_id, a.title, a.slug, a.assignment_type, a.assignment_number, Math.round(a.display_order), a.due_date, a.description, a.created_at])).join(',\n')}
  ) as v (id, course_offering_id, title, slug, assignment_type, assignment_number, display_order, due_date, description, created_at)
  join public.course_offerings o on o.id = v.course_offering_id::uuid
on conflict do nothing;

-- Demo problems (parents are listed before their parts).
insert into public.problems (id, assignment_id, parent_problem_id, label, slug, display_order, title, statement_markdown,
                             statement_source, extraction_status, created_by)
select v.id::uuid, a.id, v.parent_problem_id::uuid, v.label, v.slug, v.display_order::int, v.title, v.statement_markdown,
       case when v.statement_markdown is null then 'none' else 'manual' end::public.statement_source,
       case when v.statement_markdown is null then 'none' else 'reviewed' end::public.extraction_status,
       null
  from (values
${ds.problems.map((p) => row([p.id, p.assignment_id, p.parent_problem_id, p.label, p.slug, p.display_order, p.title, p.statement_markdown])).join(',\n')}
  ) as v (id, assignment_id, parent_problem_id, label, slug, display_order, title, statement_markdown)
  join public.assignments a on a.id = v.assignment_id::uuid and a.is_demo
on conflict do nothing;
`)

demo.push('-- Synthetic ratings (only on leaf problems; the triggers keep problem_stats up to date).')
for (const part of chunk(ds.ratings, 500)) {
  demo.push(`insert into public.ratings (user_id, problem_id, difficulty, time_minutes, completion_status)
select v.user_id::uuid, p.id, v.difficulty::smallint, v.time_minutes::int, v.completion_status::public.completion_status
  from (values
${part.map((r) => row([r.user_id, r.problem_id, r.difficulty, r.time_minutes, r.completion_status])).join(',\n')}
  ) as v (user_id, problem_id, difficulty, time_minutes, completion_status)
  join public.problems p on p.id = v.problem_id::uuid
  join public.assignments a on a.id = p.assignment_id and a.is_demo
on conflict (user_id, problem_id) do nothing;
`)
}

demo.push(`-- Recompute aggregates for every demo problem (also creates empty stats rows for unrated problems).
do $$
declare r record;
begin
  for r in select p.id from public.problems p join public.assignments a on a.id = p.assignment_id where a.is_demo loop
    perform private.refresh_problem_stats(r.id);
  end loop;
end $$;

commit;
`)

const removeSql = `${GENERATED}
--
-- Removes the DEMO / SYNTHETIC data added by supabase/seed-demo.sql: demo users (profiles.is_demo) and their
-- ratings, demo assignments (assignments.is_demo) with their problems, stats, history, and any ratings on them.
-- The real catalog (universities / courses / offerings from supabase/seed.sql) is left intact.
-- Idempotent. Run as the service role / postgres.

begin;

-- Ratings first, so aggregates on any non-demo problems are recomputed by the ratings trigger.
delete from public.ratings
 where user_id in (select id from public.profiles where is_demo)
    or problem_id in (select p.id from public.problems p join public.assignments a on a.id = p.assignment_id where a.is_demo);

-- Old-slug redirects that point at demo rows.
delete from public.slug_aliases
 where entity_id in (select id from public.assignments where is_demo)
    or entity_id in (select p.id from public.problems p join public.assignments a on a.id = p.assignment_id where a.is_demo);

-- Demo assignments; their problems, problem_stats, revisions, and proposals cascade.
delete from public.assignments where is_demo;

-- Demo-only catalog rows, if any (the real catalog is never flagged is_demo).
delete from public.course_offerings where is_demo;
delete from public.courses where is_demo;
delete from public.universities where is_demo;

-- Demo users (profiles cascade).
delete from auth.users where id in (select id from public.profiles where is_demo);

commit;
`

const files: Array<[string, string]> = [
  ['supabase/seed.sql', seedSql],
  ['supabase/seed-demo.sql', demo.join('\n')],
  ['supabase/remove-demo.sql', removeSql],
]
for (const [path, sql] of files) {
  writeFileSync(resolve(ROOT, path), sql)
  console.log(`wrote ${path} (${(sql.length / 1024).toFixed(1)} KB)`)
}
console.log(
  `catalog: ${ds.universities.length} university, ${ds.courses.length} courses, ${ds.offerings.length} offerings; ` +
    `demo: ${ds.demoUserIds.length} users, ${ds.assignments.length} assignments, ${ds.problems.length} problems, ${ds.ratings.length} ratings`,
)
